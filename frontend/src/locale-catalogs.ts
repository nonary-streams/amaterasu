  function catalogFromTranslations(
    keys: readonly string[],
    translations: readonly string[] | undefined,
  ): LocaleMessages {
    const catalog: LocaleMessages = {};
    if (!translations) return catalog;
    if (translations.length !== keys.length) {
      throw new Error("The locale catalog contains an incomplete message list.");
    }
    keys.forEach((key, index) => {
      const translation = translations[index];
      if (translation !== undefined) catalog[key] = translation;
    });
    return catalog;
  }

  function englishCatalog(keys: readonly string[]): LocaleMessages {
    return Object.fromEntries(keys.map((key) => [key, key]));
  }

  export function mergeLocaleMessages(
    base: LocaleMessages,
    overlay: LocaleMessages,
  ): LocaleMessages {
    const result: LocaleMessages = { ...base };
    for (const [key, value] of Object.entries(overlay)) {
      const existing = result[key];
      result[key] =
        value &&
        typeof value === "object" &&
        !Array.isArray(value) &&
        existing &&
        typeof existing === "object" &&
        !Array.isArray(existing)
          ? mergeLocaleMessages(
              existing as LocaleMessages,
              value as LocaleMessages,
            )
          : value;
    }
    return result;
  }

  export function localeMessagesFor(locale: LocaleToken): LocaleMessages {
    const englishBase = englishCatalog(BASE_MESSAGE_KEYS);
    const englishUi = englishCatalog(UI_MESSAGE_KEYS);
    const englishShell = englishCatalog(SHELL_MESSAGE_KEYS);
    const englishProduct = englishCatalog([
      ...new Set([
        ...Object.keys(productTranslations.bg ?? {}),
        ...Object.keys(specializedTranslations.bg ?? {}),
        ...PAGE_COPY_KEYS,
        ...ATTRIBUTE_TEMPLATE_KEYS,
        ...INPUT_OVERRIDE_LABEL_KEYS,
        ...METRIC_LABEL_KEYS,
      ]),
    ]);
    const translations = localeTranslations[locale];
    const localeBase = catalogFromTranslations(
      BASE_MESSAGE_KEYS,
      translations?.base,
    );
    const localeUi = catalogFromTranslations(
      UI_MESSAGE_KEYS,
      translations?.ui,
    );
    const localeShell = catalogFromTranslations(
      SHELL_MESSAGE_KEYS,
      shellTranslations[locale],
    );
    const localePageCopy = catalogFromTranslations(
      PAGE_COPY_KEYS,
      pageCopyTranslations[locale],
    );
    const localeAttributeTemplates = catalogFromTranslations(
      ATTRIBUTE_TEMPLATE_KEYS,
      attributeTemplateTranslations[locale],
    );
    const localeInputOverrideLabels = catalogFromTranslations(
      INPUT_OVERRIDE_LABEL_KEYS,
      inputOverrideLabelTranslations[locale],
    );
    const localeMetricLabels = catalogFromTranslations(
      METRIC_LABEL_KEYS,
      metricLabelTranslations[locale],
    );
    return mergeLocaleMessages(
      mergeLocaleMessages(
        mergeLocaleMessages(
          mergeLocaleMessages(
            mergeLocaleMessages(englishBase, englishUi),
            englishShell,
          ),
          localeBase,
        ),
        mergeLocaleMessages(localeUi, localeShell),
      ),
      mergeLocaleMessages(
        mergeLocaleMessages(englishProduct, productTranslations[locale] ?? {}),
        mergeLocaleMessages(
          specializedTranslations[locale] ?? {},
          mergeLocaleMessages(
            mergeLocaleMessages(localePageCopy, localeAttributeTemplates),
            mergeLocaleMessages(localeInputOverrideLabels, localeMetricLabels),
          ),
        ),
      ),
    );
  }

  export function translateLocaleMessage(
    source: string,
    messages: LocaleMessages,
  ): string {
    const message = messages[source];
    return typeof message === "string" ? message : source;
  }
