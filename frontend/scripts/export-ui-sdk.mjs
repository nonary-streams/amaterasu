// Export declarations only; consumers never import the shell's implementation.
import ts from 'typescript';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const files=['extension_ui.ts','extension_ui_layout.ts','extension_ui_feedback.ts','extension_ui_dialog.ts','extension_ui_tabs.ts','extension_ui_charts.ts','extensions.ts'];
const declarations=[];
for(const file of files){
 const text=await readFile(`src/${file}`,'utf8');
 const source=ts.createSourceFile(file,text,ts.ScriptTarget.Latest,true);
 const module=source.statements.find(ts.isModuleDeclaration);
 for(const statement of module.body.statements){
  if((ts.isInterfaceDeclaration(statement)||ts.isTypeAliasDeclaration(statement))&&
    (statement.modifiers?.some(modifier=>modifier.kind===ts.SyntaxKind.ExportKeyword)||['ExtensionPage','ExtensionMethod'].includes(statement.name.text)))
   declarations.push(statement.getText(source).replace(/^export /,''));
 }
}
const result='// Generated by frontend/scripts/export-ui-sdk.mjs.\n// Public browser SDK contracts; no private shell renderers or routes.\ndeclare namespace AmaterasuPluginUi {\n  type Payload = Record<string, unknown>;\n'+declarations.map(value=>value.split('\n').map(line=>'  '+line).join('\n')).join('\n\n')+'\n}\ninterface Window {\n  AmaterasuExtensions: { v1: { register(id: string, page: AmaterasuPluginUi.ExtensionPage): void } };\n}\n';
await mkdir('../sdk/web',{recursive:true});
await writeFile('../sdk/web/amaterasu-ui.d.ts',result);
